/* ==========================================================================
   作业稳定引用键 —— 浏览器端（报告 2.1）
   ==========================================================================

   每条社区作业有一个本项目自有的短引用键（形如 7b95a9a0-qfxx），供：
     · 研究结论 / 观察记录 / 对照指认作业
     · 深链 #explore?job=<引用键> 直达灯箱

   ## 键的构造

       <作业标识前 8 位>-<提示词归一化哈希前 4 位>

   两段各有分工：
     · 前 8 位标识「是哪一条」——上游标识一次生成、跨批次重采不变，
       且 collect-explore.ts 的 mergeJobs 按 id 去重（base 优先），
       同一条作业在快照中永远只有一条、批次取首次采集那天 → 键不随重采搬家。
     · 哈希前 4 位标识「内容是否变过」——上游若改了同一条作业的提示词正文，
       哈希会变 → 键会变 → 引用旧键的人会发现内容对不上，
       而不是拿到一条被悄悄改写过的作业。

   ## 为什么不用纯提示词哈希

   实测 971 条作业里，提示词归一化哈希有 34 组碰撞（社区里大量重复提示词：
   同一句模板被不同作者反复用）。纯提示词哈希做不了主键。

   ## 为什么不用纯 id 前 8 位

   8 位十六进制（32 bit）在 971 条上零碰撞，但那是运气不是保证：
   32 bit 在约 7.7 万条时碰撞概率就约 50%。加上哈希段后有效位宽 48 bit。

   ## 为什么键在前端算、而不是构建期烘焙进产物

   键是「由作业标识与提示词推导出来的量」，不是**采集来的事实**。
   烘焙进 data-explore.js 会让「改一行前端代码」变成「6 MB 生成物跟着漂移」，
   diff 会被采集数据的变化淹没。本文件是纯函数、无依赖，
   在运行时由 id 与 prompt 现算 —— 算法只有这一份，不存在两处漂移。

   构建期仍会用 tools/job-key.mjs 跑一遍**碰撞断言**（同一套算法，
   唯一差别是构建期那份多一个批量版本），确保全表零碰撞。

   ## 哈希算法

   FNV-1a 32 位，同步、零依赖。不用 crypto.subtle —— file:// 打开页面时
   不保证安全上下文，crypto.subtle 会是 undefined。与 explore-board.js
   里收藏键用的 favKey() 同一算法，保持全站一致。
   ========================================================================== */

const JOB_KEY = (() => {
  /** 提示词归一化：折叠空白 + 转小写 + 去首尾。 */
  function normalizePrompt(prompt) {
    return String(prompt ?? '')
      .trim()
      .replace(/\s+/g, ' ')
      .toLowerCase();
  }

  /** FNV-1a 32 位哈希 → 36 进制字符串。 */
  function fnv1a(str) {
    let h = 0x811c9dc5;
    for (let i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = Math.imul(h, 0x01000193);
    }
    return (h >>> 0).toString(36);
  }

  /** 一条作业的引用键。 */
  function keyOf(job) {
    const id8 = String(job?.id ?? '').slice(0, 8) || '????????';
    const h = fnv1a(normalizePrompt(job?.prompt)).slice(0, 4);
    return `${id8}-${h}`;
  }

  return { normalizePrompt, fnv1a, keyOf };
})();
