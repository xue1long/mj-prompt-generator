<template>
  <div class="final-prompt">
    <div v-if="autoGeneratedPrompt || editedPrompt" class="prompt-editor">
      <n-input
        v-model:value="editedPrompt"
        type="textarea"
        placeholder="选择提示词和参数后将自动生成，也可以在此直接编辑..."
        :autosize="{ minRows: 5, maxRows: 8 }"
        @update:value="handleEdit"
      />
      <div v-if="isManuallyEdited" class="edit-hint">
        <span class="hint-icon">✏️</span>
        <span class="hint-text">已手动编辑</span>
        <n-button text @click="handleReset" class="reset-link">
          重置为自动生成
        </n-button>
      </div>
    </div>

    <div v-else class="empty-state">
      <span class="empty-icon">✨</span>
      <span class="empty-text">选择提示词和参数后将在这里显示</span>
    </div>

    <div class="actions">
      <n-button
        type="primary"
        :disabled="!currentPrompt"
        @click="handleCopy"
        class="copy-btn"
      >
        <template #icon>
          <span>📋</span>
        </template>
        {{ copied ? '已复制!' : '复制提示词' }}
      </n-button>

      <n-button
        :disabled="!hasContent"
        @click="handleClear"
        secondary
      >
        <template #icon>
          <span>🗑️</span>
        </template>
        清空所有
      </n-button>
    </div>

    <div v-if="currentPrompt" class="prompt-info">
      <span class="info-item">
        <span class="info-label">提示词数量:</span>
        <span class="info-value">{{ selectedCount }}</span>
      </span>
      <span class="info-item">
        <span class="info-label">字符数:</span>
        <span class="info-value">{{ currentPrompt.length }}</span>
      </span>
    </div>
  </div>
</template>

<script setup lang="ts">
import { computed, ref, watch } from 'vue'
import { NButton, NInput } from 'naive-ui'
import { storeToRefs } from 'pinia'
import { usePromptStore } from '@/stores/promptStore'
import { useParameterStore } from '@/stores/parameterStore'
import { PromptBuilder } from '@/utils/promptBuilder'

const promptStore = usePromptStore()
const parameterStore = useParameterStore()

const { selectedPrompts, subjectEnvironment } = storeToRefs(promptStore)
const { values, config: parameterConfig } = storeToRefs(parameterStore)

const copied = ref(false)
const editedPrompt = ref('')
const isManuallyEdited = ref(false)

// 计算属性：自动生成的提示词
const autoGeneratedPrompt = computed(() => {
  if (selectedPrompts.value.length === 0 && !subjectEnvironment.value.trim()) {
    return ''
  }

  // 使用摄影专用构建器
  return PromptBuilder.buildPhotography(
    selectedPrompts.value,
    subjectEnvironment.value,
    values.value,
    parameterConfig.value ?? undefined
  )
})

// 当前使用的提示词（手动编辑优先）
const currentPrompt = computed(() => {
  return editedPrompt.value || autoGeneratedPrompt.value
})

// 监听自动生成的提示词变化
watch(autoGeneratedPrompt, (newVal) => {
  // 只有在未手动编辑时才自动同步
  if (!isManuallyEdited.value) {
    editedPrompt.value = newVal
  }
}, { immediate: true })

// 计算属性：选中的提示词数量
const selectedCount = computed(() => {
  return selectedPrompts.value.length
})

// 计算属性：是否有内容
const hasContent = computed(() => {
  return selectedPrompts.value.length > 0 ||
         subjectEnvironment.value.trim().length > 0 ||
         Object.keys(values.value).length > 0
})

// 处理手动编辑
const handleEdit = () => {
  isManuallyEdited.value = true
}

// 重置为自动生成
const handleReset = () => {
  isManuallyEdited.value = false
  editedPrompt.value = autoGeneratedPrompt.value
}

// 复制到剪贴板
const handleCopy = async () => {
  if (!currentPrompt.value) return

  try {
    await navigator.clipboard.writeText(currentPrompt.value)
    copied.value = true

    // 2秒后重置状态
    setTimeout(() => {
      copied.value = false
    }, 2000)
  } catch (error) {
    console.error('复制失败:', error)
    // 降级方案：使用传统方法
    const textarea = document.createElement('textarea')
    textarea.value = currentPrompt.value
    textarea.style.position = 'fixed'
    textarea.style.opacity = '0'
    document.body.appendChild(textarea)
    textarea.select()
    document.execCommand('copy')
    document.body.removeChild(textarea)

    copied.value = true
    setTimeout(() => {
      copied.value = false
    }, 2000)
  }
}

// 清空所有选项
const handleClear = () => {
  promptStore.clearAll()
  parameterStore.resetToDefaults()
  editedPrompt.value = ''
  isManuallyEdited.value = false
}
</script>

